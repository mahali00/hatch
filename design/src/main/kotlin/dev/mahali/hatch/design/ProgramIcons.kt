package dev.mahali.hatch.design

import androidx.annotation.DrawableRes
import androidx.compose.ui.graphics.Color

/** Sources are listed in design/ICONS.md. */
internal sealed interface ProgramIcon {
    /** Only one-colour vector logos can be tinted; bitmaps cannot. */
    data class Logo(@param:DrawableRes val drawable: Int, val background: Color, val scale: Float, val tintable: Boolean) : ProgramIcon

    /** Programs with no public logo: the terminal prompt on a dark tile. */
    data object Generic : ProgramIcon
}

// Simple Icons are 24-unit marks drawn 26 px wide on Paper's 48 px tile; favicons 32 px. A scale of
// 1 is a logo that brings its own padding and fills the tile.
private const val MARK_SCALE = 26f / 48f
private const val FAVICON_SCALE = 32f / 48f

private fun vector(@DrawableRes drawable: Int, background: Long, scale: Float = MARK_SCALE) =
    ProgramIcon.Logo(drawable, Color(background), scale, tintable = true)

private fun bitmap(@DrawableRes drawable: Int, background: Long, scale: Float = FAVICON_SCALE) =
    ProgramIcon.Logo(drawable, Color(background), scale, tintable = false)

